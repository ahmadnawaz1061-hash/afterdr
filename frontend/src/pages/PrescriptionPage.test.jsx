import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { act, cleanup, fireEvent, render, screen, within } from '@testing-library/react';
import PrescriptionPage from './PrescriptionPage';
import { extractPrescription, savePrescription } from '../services/api';
import { demoPrescription } from '../mocks/demoData';

vi.mock('../services/api', () => ({ extractPrescription: vi.fn(), savePrescription: vi.fn() }));

beforeEach(() => {
  extractPrescription.mockReset();
  savePrescription.mockReset();
  savePrescription.mockResolvedValue({ prescription_id: 42, status: 'confirmed', medicine_count: 2 });
  vi.stubGlobal('requestAnimationFrame', (callback) => callback());
  vi.stubGlobal('URL', class extends URL {
    static createObjectURL = vi.fn(() => 'blob:preview');
    static revokeObjectURL = vi.fn();
  });
});
afterEach(() => { cleanup(); vi.unstubAllGlobals(); });

function chooseImage() {
  const file = new File(['image bytes'], 'prescription.png', { type: 'image/png' });
  fireEvent.change(screen.getByLabelText('Prescription image'), { target: { files: [file] } });
  return file;
}

it('uploads with the service, shows loading, then renders editable review rows', async () => {
  let resolveRequest;
  extractPrescription.mockReturnValue(new Promise((resolve) => { resolveRequest = resolve; }));
  render(<PrescriptionPage />);
  const file = chooseImage();
  fireEvent.click(screen.getByRole('button', { name: 'Read prescription' }));
  expect(extractPrescription).toHaveBeenCalledWith(file);
  const review = screen.getByRole('region', { name: '2. Review extracted instructions' });
  expect(within(review).getByRole('status').textContent).toContain('Reading the prescription');
  expect(screen.getByLabelText('Prescription image').disabled).toBe(true);
  await act(async () => resolveRequest({ ...demoPrescription, simulated: true }));
  expect(screen.getByText('This extraction was generated by the backend demonstration stub.')).toBeTruthy();
  expect(screen.getAllByText('Simulated demo data')).toHaveLength(1);
  expect(screen.getAllByRole('group')).toHaveLength(2);
  expect(screen.getAllByText(/Needs review/)).toHaveLength(2);
  const firstRow = screen.getAllByRole('group')[0];
  fireEvent.change(within(firstRow).getByLabelText('Medicine'), { target: { value: 'Corrected Demo Medicine' } });
  expect(within(firstRow).getByLabelText('Medicine').value).toBe('Corrected Demo Medicine');
  fireEvent.click(screen.getByRole('button', { name: 'Confirm reviewed instructions' }));
  expect((await within(review).findByRole('status')).textContent).toContain('Prescription saved to your account.');
  expect(savePrescription).toHaveBeenCalledWith(expect.objectContaining({
    status: 'confirmed',
    medicines: expect.arrayContaining([expect.objectContaining({ name: 'Corrected Demo Medicine', needs_review: false })]),
  }));
  expect(screen.queryByRole('button', { name: 'Confirm reviewed instructions' })).toBeNull();
});

it('shows backend detail and retries the same selected file', async () => {
  extractPrescription
    .mockRejectedValueOnce({ response: { data: { detail: 'Uploaded image could not be processed.' } } })
    .mockResolvedValueOnce({ ...demoPrescription, simulated: true });
  render(<PrescriptionPage />);
  const file = chooseImage();
  fireEvent.click(screen.getByRole('button', { name: 'Read prescription' }));
  const review = screen.getByRole('region', { name: '2. Review extracted instructions' });
  expect((await within(review).findByRole('alert')).textContent).toContain('Uploaded image could not be processed.');
  fireEvent.click(screen.getByRole('button', { name: 'Try again' }));
  expect(extractPrescription).toHaveBeenLastCalledWith(file);
  expect(await screen.findByText('This extraction was generated by the backend demonstration stub.')).toBeTruthy();
});

it('handles an empty result and resets output when the image is removed', async () => {
  extractPrescription.mockResolvedValue({ status: 'needs_review', medicines: [], is_demo: true, simulated: true });
  render(<PrescriptionPage />);
  chooseImage();
  fireEvent.click(screen.getByRole('button', { name: 'Read prescription' }));
  expect(await screen.findByText('No medicine instructions were found. Try a clearer image.')).toBeTruthy();
  fireEvent.click(screen.getByRole('button', { name: 'Remove image' }));
  expect(screen.getByText(/Choose an image and select/)).toBeTruthy();
  expect(screen.getByRole('button', { name: 'Read prescription' }).disabled).toBe(true);
});
