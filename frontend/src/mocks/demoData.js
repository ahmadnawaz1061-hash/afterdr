export const DEMO_TIME_ZONE = 'Asia/Karachi';

// These doses represent a separate, already-confirmed demo prescription.
// They are never generated by confirming the extraction fixture above.
export function createDemoTodaySchedule(now = new Date()) {
  const dateParts = Object.fromEntries(new Intl.DateTimeFormat('en-US', {
    timeZone: DEMO_TIME_ZONE, year: 'numeric', month: '2-digit', day: '2-digit',
  }).formatToParts(now).map(({ type, value }) => [type, value]));
  const date = `${dateParts.year}-${dateParts.month}-${dateParts.day}`;
  const timestamp = (time) => new Date(`${date}T${time}:00+05:00`).toISOString();

  return [
    { id: 301, prescription_item_id: 201, medicine_name: 'Demo Medicine A', scheduled_at: timestamp('09:00'), local_time: '09:00', status: 'taken', taken_at: timestamp('09:05'), is_demo: true },
    { id: 302, prescription_item_id: 202, medicine_name: 'Demo Medicine C', scheduled_at: timestamp('14:00'), local_time: '14:00', status: 'missed', taken_at: null, is_demo: true },
    { id: 303, prescription_item_id: 201, medicine_name: 'Demo Medicine A', scheduled_at: timestamp('21:00'), local_time: '21:00', status: 'pending', taken_at: null, is_demo: true },
  ];
}

